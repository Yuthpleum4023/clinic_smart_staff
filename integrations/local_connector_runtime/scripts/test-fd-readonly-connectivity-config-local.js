"use strict";
const assert = require("assert");
const { FD_DATABASE, FD_PORT, FD_PASSWORD_ENV, buildFdReadOnlyConnectivityConfig, assertFdReadOnlyConnectivityConfig } = require("../src/connectivity/fd/fdReadOnlyConnectionConfig");
assert.equal(FD_DATABASE, "FD5_5");
assert.equal(FD_PORT, 3306);
assert.equal(FD_PASSWORD_ENV, "CLINIC_SOURCE_DB_PASSWORD");
assert.throws(() => buildFdReadOnlyConnectivityConfig({ host: "", user: "fd_user" }), /FD_SOURCE_HOST_REQUIRED/);
assert.throws(() => buildFdReadOnlyConnectivityConfig({ host: "fd-db-host", user: "" }), /FD_SOURCE_USER_REQUIRED/);
const config = buildFdReadOnlyConnectivityConfig({ host: "deployment-supplied-host", user: "deployment-supplied-user" });
assert.equal(assertFdReadOnlyConnectivityConfig(config), true);
assert.equal(config.source.database, "FD5_5");
assert.equal(config.source.port, 3306);
assert.equal("password" in config.source, false);
assert.equal("clinicId" in config, false);
assert.equal("connectorToken" in config, false);
assert.equal("adapterProfile" in config, false);
assert.throws(() => assertFdReadOnlyConnectivityConfig({ ...config, source: { ...config.source, password: "must-never-be-here" } }), /FD_PASSWORD_MUST_NOT_BE_EMBEDDED/);
assert.throws(() => assertFdReadOnlyConnectivityConfig({ ...config, source: { ...config.source, database: "wrong_database" } }), /FD_DATABASE_CONTRACT_MISMATCH/);
console.log("FD_REAL_CONNECTIVITY_CONFIG_TESTS_PASSED=TRUE");
console.log("FD_DATABASE_LOCKED_TO_FD5_5=TRUE");
console.log("FD_PORT_LOCKED_TO_3306=TRUE");
console.log("FD_HOST_DEPLOYMENT_SUPPLIED=TRUE");
console.log("FD_USER_DEPLOYMENT_SUPPLIED=TRUE");
console.log("FD_PASSWORD_ENV_ONLY=TRUE");
console.log("CONNECTOR_TOKEN_REQUIRED=FALSE");
console.log("FD_ADAPTER_REQUIRED=FALSE");
console.log("BUSINESS_POLL_SPEC_REQUIRED=FALSE");
console.log("REAL_NETWORK_CONNECTION_ATTEMPTED=FALSE");
