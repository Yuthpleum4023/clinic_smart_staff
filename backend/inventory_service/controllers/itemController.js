exports.updateItem =
  async (req, res, next) => {
    try {
      const actor =
        await resolveInventoryActor(req);

      if (!actor.hasAdmin) {
        const err =
          new Error("Admin only");

        err.status = 403;
        err.code = "ADMIN_ONLY";
        throw err;
      }

      if (
        Object.prototype
          .hasOwnProperty.call(
            req.body || {},
            "sku"
          )
      ) {
        throw bad(
          "Item code is generated by inventory_service",
          "SYSTEM_ITEM_CODE_MANAGED_BY_SERVER"
        );
      }

      const forbidden = [
        "currentQty",
        "balance",
        "quantity",
        "minimumQty",
        "lowStockActive",
        "lowStockSince",
      ];

      if (
        forbidden.some((k) =>
          Object.prototype
            .hasOwnProperty.call(
              req.body || {},
              k
            )
        )
      ) {
        throw bad(
          "Balance and threshold fields cannot be changed through item update",
          "PROTECTED_STOCK_FIELD"
        );
      }

      if (
        !mongoose.Types.ObjectId.isValid(
          req.params.id
        )
      ) {
        throw bad(
          "Invalid item id",
          "INVALID_STOCK_ITEM_ID"
        );
      }

      const patch = {
        updatedBy:
          actor.userId,
      };

      for (
        const key of [
          "name",
          "category",
          "unit",
        ]
      ) {
        if (
          Object.prototype
            .hasOwnProperty.call(
              req.body || {},
              key
            )
        ) {
          patch[key] =
            s(req.body[key]);
        }
      }

      if (
        Object.prototype
          .hasOwnProperty.call(
            req.body || {},
            "active"
          )
      ) {
        if (
          typeof req.body.active !==
          "boolean"
        ) {
          throw bad(
            "active must be boolean",
            "INVALID_ACTIVE_VALUE"
          );
        }

        patch.active =
          req.body.active;
      }

      if (patch.name === "") {
        throw bad(
          "name must not be empty",
          "INVALID_NAME"
        );
      }

      if (patch.unit === "") {
        throw bad(
          "unit must not be empty",
          "INVALID_UNIT"
        );
      }

      const item =
        await StockItem.findOneAndUpdate(
          {
            _id: req.params.id,
            clinicId:
              actor.clinicId,
          },
          { $set: patch },
          {
            new: true,
            runValidators: true,
          }
        );

      if (!item) {
        const err =
          new Error(
            "Stock item not found"
          );

        err.status = 404;
        err.code =
          "STOCK_ITEM_NOT_FOUND";

        throw err;
      }

      return res.json({
        ok: true,
        item:
          serializeItem(item),
      });
    } catch (err) {
      return next(err);
    }
  };

exports.updateThreshold =
  async (req, res, next) => {
    try {
      const actor =
        await resolveInventoryActor(req);

      if (!actor.hasAdmin) {
        const err =
          new Error("Admin only");

        err.status = 403;
        err.code = "ADMIN_ONLY";
        throw err;
      }

      if (
        !mongoose.Types.ObjectId.isValid(
          req.params.id
        )
      ) {
        throw bad(
          "Invalid item id",
          "INVALID_STOCK_ITEM_ID"
        );
      }

      const minimumQty =
        qty(
          req.body?.minimumQty,
          "minimumQty"
        );

      if (minimumQty < 0) {
        throw bad(
          "minimumQty must be >= 0",
          "INVALID_MINIMUM_QTY"
        );
      }

      const item =
        await StockItem.findOne({
          _id: req.params.id,
          clinicId:
            actor.clinicId,
        });

      if (!item) {
        const err =
          new Error(
            "Stock item not found"
          );

        err.status = 404;
        err.code =
          "STOCK_ITEM_NOT_FOUND";

        throw err;
      }

      if (
        Object.prototype
          .hasOwnProperty.call(
            req.body || {},
            "lowStockAlertEnabled"
          )
      ) {
        item.lowStockAlertEnabled =
          !!req.body
            .lowStockAlertEnabled;
      }

      item.minimumQty =
        minimumQty;

      item.updatedBy =
        actor.userId;

      const nowLow =
        item.lowStockAlertEnabled &&
        Number(item.currentQty) <=
          Number(item.minimumQty);

      const wasLow =
        !!item.lowStockActive;

      item.lowStockActive =
        nowLow;

      if (!wasLow && nowLow) {
        item.lowStockSince =
          new Date();
      }

      if (wasLow && !nowLow) {
        item.lowStockSince =
          null;
      }

      await item.save();

      return res.json({
        ok: true,
        item:
          serializeItem(item),
      });
    } catch (err) {
      return next(err);
    }
  };

