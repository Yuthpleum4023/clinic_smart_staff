const mongoose = require("mongoose");
const StockItem = require("../models/StockItem");
const StockMovement = require("../models/StockMovement");
const { allocateInventoryItemCode } = require("../services/itemCodeService");

const {
  resolveInventoryActor,
} = require("../services/actorService");

const { qty } = require("../utils/quantity");
const { s } = require("../utils/strings");

function bad(
  message,
  code = "BAD_REQUEST"
) {
  const err = new Error(message);
  err.status = 400;
  err.code = code;
  return err;
}

function serializeItem(item) {
  return item?.toObject
    ? item.toObject()
    : item;
}

exports.createItem =
  async (req, res, next) => {
    try {
      const actor =
        await resolveInventoryActor(req);

      if (!actor.hasAdmin) {
        const err =
          new Error("Admin only");

        err.status = 403;
        err.code = "ADMIN_ONLY";
        throw err;
      }

      const name = s(req.body?.name);
      const unit = s(req.body?.unit);

      if (
        Object.prototype.hasOwnProperty.call(
          req.body || {},
          "sku"
        )
      ) {
        throw bad(
          "Item code is generated by inventory_service",
          "SYSTEM_ITEM_CODE_MANAGED_BY_SERVER"
        );
      }

      if (!name) {
        throw bad(
          "name is required",
          "NAME_REQUIRED"
        );
      }

      if (!unit) {
        throw bad(
          "unit is required",
          "UNIT_REQUIRED"
        );
      }

      if (
        req.body?.currentQty !==
          undefined ||
        req.body?.balance !==
          undefined ||
        req.body?.quantity !==
          undefined
      ) {
        throw bad(
          "Initial balance must be recorded through stock-in, not item creation",
          "DIRECT_BALANCE_WRITE_FORBIDDEN"
        );
      }

      const minimumQty =
        req.body?.minimumQty ===
        undefined
          ? 0
          : qty(
              req.body.minimumQty,
              "minimumQty"
            );

      if (minimumQty < 0) {
        throw bad(
          "minimumQty must be >= 0",
          "INVALID_MINIMUM_QTY"
        );
      }

      const lowStockAlertEnabled =
        req.body
          ?.lowStockAlertEnabled ===
        undefined
          ? true
          : !!req.body
              .lowStockAlertEnabled;

      // INVENTORY_SERVER_ITEM_CODE_V2
      const itemCode =
        await allocateInventoryItemCode({
          clinicId: actor.clinicId,
        });

      const item =
        await StockItem.create({
          clinicId:
            actor.clinicId,

          name,
          sku: itemCode,
          category:
            s(req.body?.category),
          unit,

          currentQty: 0,
          minimumQty,

          lowStockAlertEnabled,

          lowStockActive:
            lowStockAlertEnabled &&
            0 <= minimumQty,

          lowStockSince:
            lowStockAlertEnabled &&
            0 <= minimumQty
              ? new Date()
              : null,

          active:
            req.body?.active ===
            undefined
              ? true
              : !!req.body.active,

          createdBy:
            actor.userId,

          updatedBy:
            actor.userId,
        });

      return res
        .status(201)
        .json({
          ok: true,
          item:
            serializeItem(item),
        });
    } catch (err) {
      return next(err);
    }
  };

exports.listItems =
  async (req, res, next) => {
    try {
      await resolveInventoryActor(req);

      const q = {
        clinicId:
          req.inventoryClinicId,
      };

      const activeParam =
        s(req.query?.active)
          .toLowerCase();

      if (activeParam) {
        if (
          activeParam !== "true" &&
          activeParam !== "false"
        ) {
          throw bad(
            "active must be true or false",
            "INVALID_ACTIVE_FILTER"
          );
        }

        q.active =
          activeParam === "true";
      }

      const lowStockParam =
        s(req.query?.lowStock)
          .toLowerCase();

      if (lowStockParam) {
        if (
          lowStockParam !== "true" &&
          lowStockParam !== "false"
        ) {
          throw bad(
            "lowStock must be true or false",
            "INVALID_LOW_STOCK_FILTER"
          );
        }

        q.lowStockActive =
          lowStockParam === "true";

        if (
          lowStockParam === "true"
        ) {
          q.lowStockAlertEnabled =
            true;

          if (
            typeof q.active ===
            "undefined"
          ) {
            q.active = true;
          }
        }
      }

      const search =
        s(req.query?.search);

      if (search) {
        if (search.length > 120) {
          throw bad(
            "search must not exceed 120 characters",
            "INVALID_ITEM_SEARCH"
          );
        }

        const escapedSearch =
          search.replace(
            /[.*+?^${}()|[\]\\]/g,
            "\\$&"
          );

        const searchPattern =
          new RegExp(
            escapedSearch,
            "i"
          );

        q.$or = [
          { name: searchPattern },
          { sku: searchPattern },
          { category: searchPattern },
        ];
      }

      const items =
        await StockItem.find(q)
          .sort({
            active: -1,
            name: 1,
          })
          .lean();

      return res.json({
        ok: true,
        items,
      });
    } catch (err) {
      return next(err);
    }
  };

