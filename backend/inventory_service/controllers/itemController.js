exports.getStockCard =
  async (req, res, next) => {
    try {
      const actor =
        await resolveInventoryActor(req);

      if (
        !mongoose.Types.ObjectId.isValid(
          req.params.id
        )
      ) {
        throw bad(
          "Invalid item id",
          "INVALID_STOCK_ITEM_ID"
        );
      }

      const item =
        await StockItem.findOne({
          _id: req.params.id,
          clinicId:
            req.inventoryClinicId,
        }).lean();

      if (!item) {
        const err =
          new Error(
            "Stock item not found"
          );

        err.status = 404;
        err.code =
          "STOCK_ITEM_NOT_FOUND";

        throw err;
      }

      function parseDate(
        raw,
        field
      ) {
        if (!s(raw)) {
          return null;
        }

        const d = new Date(raw);

        if (
          Number.isNaN(
            d.getTime()
          )
        ) {
          throw bad(
            `${field} must be a valid date`,
            "INVALID_DATE_RANGE"
          );
        }

        return d;
      }

      const from =
        parseDate(
          req.query?.from,
          "from"
        );

      const to =
        parseDate(
          req.query?.to,
          "to"
        );

      if (
        from &&
        to &&
        from > to
      ) {
        throw bad(
          "from must be before or equal to to",
          "INVALID_DATE_RANGE"
        );
      }

      const mode =
        s(
          req.query?.mode ||
            "operational"
        ).toLowerCase();

      if (
        ![
          "operational",
          "financial",
        ].includes(mode)
      ) {
        throw bad(
          "mode must be operational or financial",
          "INVALID_STOCK_CARD_MODE"
        );
      }

      if (
        mode === "financial" &&
        !actor.hasAdmin
      ) {
        const err =
          new Error(
            "Financial Stock Card is admin only"
          );

        err.status = 403;
        err.code =
          "FINANCIAL_STOCK_CARD_ADMIN_ONLY";

        throw err;
      }

      const limit =
        Math.min(
          Math.max(
            Number(
              req.query?.limit
            ) || 500,
            1
          ),
          2000
        );

      const q = {
        clinicId:
          req.inventoryClinicId,
        stockItemId:
          item._id,
      };

      if (from || to) {
        q.createdAt = {};

        if (from) {
          q.createdAt.$gte =
            from;
        }

        if (to) {
          q.createdAt.$lte =
            to;
        }
      }

      const [
        movements,
        totalCount,
        firstInRange,
        lastInRange,
        grouped,
      ] = await Promise.all([
        StockMovement.find(q)
          .sort({
            createdAt: 1,
            _id: 1,
          })
          .limit(limit)
          .lean(),

        StockMovement.countDocuments(q),

        StockMovement.findOne(q)
          .sort({
            createdAt: 1,
            _id: 1,
          })
          .lean(),

        StockMovement.findOne(q)
          .sort({
            createdAt: -1,
            _id: -1,
          })
          .lean(),

        StockMovement.aggregate([
          { $match: q },
          {
            $group: {
              _id: "$type",
              qty: {
                $sum:
                  "$quantityDelta",
              },
              count: { $sum: 1 },
            },
          },
        ]),
      ]);

      let openingBalance = 0;

      if (firstInRange) {
        openingBalance =
          Number(
            firstInRange
              .balanceBefore || 0
          );
      } else if (from) {
        const previous =
          await StockMovement.findOne({
            clinicId:
              req.inventoryClinicId,

            stockItemId:
              item._id,

            createdAt: {
              $lt: from,
            },
          })
            .sort({
              createdAt: -1,
              _id: -1,
            })
            .lean();

        openingBalance =
          previous
            ? Number(
                previous
                  .balanceAfter || 0
              )
            : 0;
      } else if (!to) {
        openingBalance =
          Number(
            item.currentQty || 0
          );
      }

      const closingBalance =
        lastInRange
          ? Number(
              lastInRange
                .balanceAfter || 0
            )
          : from || to
            ? openingBalance
            : Number(
                item.currentQty || 0
              );

      let stockInQty = 0;
      let consumptionQty = 0;
      let adjustmentNetQty = 0;
      let reversalNetQty = 0;

      for (const row of grouped) {
        const value =
          Number(row.qty || 0);

        if (
          row._id ===
          "stock_in"
        ) {
          stockInQty +=
            Math.max(
              value,
              0
            );
        } else if (
          row._id ===
            "manual_consumption" ||
          row._id ===
            "external_consumption"
        ) {
          consumptionQty +=
            Math.abs(
              Math.min(
                value,
                0
              )
            );
        } else if (
          row._id ===
          "adjustment"
        ) {
          adjustmentNetQty +=
            value;
        } else if (
          row._id ===
          "reversal"
        ) {
          reversalNetQty +=
            value;
        }
      }

      function serializeMovement(
        movement
      ) {
        const out = {
          ...movement,
        };

        if (
          mode !== "financial"
        ) {
          delete out.unitCost;
          delete out.currency;
        }

        const delta =
          Number(
            out.quantityDelta ||
              0
          );

        out.cardColumns = {
          receivedQty:
            out.type ===
              "stock_in" &&
            delta > 0
              ? delta
              : 0,

          issuedQty:
            (
              out.type ===
                "manual_consumption" ||
              out.type ===
                "external_consumption"
            ) &&
            delta < 0
              ? Math.abs(delta)
              : 0,

          adjustmentQty:
            out.type ===
              "adjustment" ||
            out.type ===
              "reversal"
              ? delta
              : 0,
        };

        if (
          mode ===
            "financial" &&
          out.unitCost !== null &&
          out.unitCost !== undefined
        ) {
          out.totalCost =
            Math.round(
              Math.abs(delta) *
                Number(
                  out.unitCost
                ) *
                100
            ) / 100;
        }

        return out;
      }

      return res.json({
        ok: true,

        stockCard: {
          mode,

          clinicId:
            req.inventoryClinicId,

          generatedAt:
            new Date(),

          generatedBy: {
            userId:
              actor.userId,
            staffId:
              actor.staffId,
            name:
              actor.displayName,
            role:
              actor.role,
          },

          item: {
            _id: item._id,
            name: item.name,
            sku: item.sku,
            category:
              item.category,
            unit: item.unit,

            currentQty:
              item.currentQty,

            minimumQty:
              item.minimumQty,

            lowStockAlertEnabled:
              item
                .lowStockAlertEnabled,

            lowStockActive:
              item.lowStockActive,

            active:
              item.active,
          },

          period: {
            basis:
              "ledger_created_at",
            from,
            to,
          },

          openingBalance,
          closingBalance,

          summary: {
            movementCount:
              totalCount,
            stockInQty,
            consumptionQty,
            adjustmentNetQty,
            reversalNetQty,
          },

          movements:
            movements.map(
              serializeMovement
            ),

          truncated:
            totalCount >
            movements.length,

          returnedCount:
            movements.length,

          totalCount,
          limit,
        },
      });
    } catch (err) {
      return next(err);
    }
  };
